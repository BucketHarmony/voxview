#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_the_declared_size() {
        for (i, rows) in GLYPHS.iter().enumerate() {
            for row in rows {
                assert_eq!(
                    row.len(),
                    GLYPH_W,
                    "glyph {:?} has a row of the wrong width",
                    char::from(0x20 + i as u8)
                );
                assert!(row.bytes().all(|b| b == b'#' || b == b'.'));
            }
        }
    }

    #[test]
    fn atlas_is_the_right_size_and_has_a_solid_cell() {
        let px = atlas_pixels();
        assert_eq!(px.len(), (ATLAS_W * ATLAS_H) as usize);
        let cx = (SOLID_CELL % COLS) * CELL_W;
        let cy = (SOLID_CELL / COLS) * CELL_H;
        for y in cy..cy + CELL_H {
            for x in cx..cx + CELL_W {
                assert_eq!(px[(y * ATLAS_W + x) as usize], 255);
            }
        }
    }

    #[test]
    fn space_is_blank_and_letters_are_not() {
        let px = atlas_pixels();
        let ink = |c: char| {
            let cell = glyph_cell(c);
            let cx = (cell % COLS) * CELL_W;
            let cy = (cell / COLS) * CELL_H;
            (0..CELL_H)
                .flat_map(|y| (0..CELL_W).map(move |x| (x, y)))
                .filter(|(x, y)| px[((cy + y) * ATLAS_W + cx + x) as usize] != 0)
                .count()
        };
        assert_eq!(ink(' '), 0);
        assert!(ink('A') > 5);
        assert!(ink('0') > 5);
        // Unmapped characters fall back to '?'.
        assert_eq!(glyph_cell('\u{2603}'), glyph_cell('?'));
    }
}
