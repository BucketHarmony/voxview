//! A 5x7 bitmap font, drawn here rather than loaded.
//!
//! The HUD needs text and nothing else, so an embedded bitmap font avoids
//! pulling in a font rasteriser and a `.ttf` blob, and it stays pixel-crisp at
//! integer scales -- which is what you want when you are reading dimensions
//! off a debug overlay. Glyphs are written as ASCII art so they can be checked
//! by eye.

/// Glyph cell size in texels: a 5x7 glyph plus one column and row of padding.
pub const CELL_W: u32 = 6;
pub const CELL_H: u32 = 8;
const GLYPH_W: usize = 5;
const GLYPH_H: usize = 7;

/// Atlas layout: 16 columns by 6 rows covers the 95 printable ASCII glyphs
/// plus one spare cell, which is filled solid for drawing HUD backgrounds.
pub const COLS: u32 = 16;
pub const ROWS: u32 = 6;
pub const ATLAS_W: u32 = COLS * CELL_W;
pub const ATLAS_H: u32 = ROWS * CELL_H;
/// Index of the all-white cell.
pub const SOLID_CELL: u32 = 95;

/// Cell index for a character; anything unprintable becomes `?`.
pub fn glyph_cell(c: char) -> u32 {
    let i = c as u32;
    if (0x20..0x7f).contains(&i) {
        i - 0x20
    } else {
        '?' as u32 - 0x20
    }
}

/// Texture coordinates of a cell as `[u0, v0, u1, v1]`.
pub fn cell_uv(cell: u32) -> [f32; 4] {
    let cell = cell.min(SOLID_CELL);
    let (cx, cy) = (cell % COLS, cell / COLS);
    let (x0, y0) = (cx * CELL_W, cy * CELL_H);
    // Half-texel inset keeps a stretched quad from sampling its neighbours.
    let (iw, ih) = (0.5 / ATLAS_W as f32, 0.5 / ATLAS_H as f32);
    [
        x0 as f32 / ATLAS_W as f32 + iw,
        y0 as f32 / ATLAS_H as f32 + ih,
        (x0 + CELL_W) as f32 / ATLAS_W as f32 - iw,
        (y0 + CELL_H) as f32 / ATLAS_H as f32 - ih,
    ]
}

/// Rasterise the whole atlas into one `R8Unorm` image.
pub fn atlas_pixels() -> Vec<u8> {
    let mut pixels = vec![0u8; (ATLAS_W * ATLAS_H) as usize];
    for (cell, rows) in GLYPHS.iter().enumerate() {
        let cx = (cell as u32 % COLS) * CELL_W;
        let cy = (cell as u32 / COLS) * CELL_H;
        for (y, row) in rows.iter().enumerate().take(GLYPH_H) {
            for (x, byte) in row.bytes().enumerate().take(GLYPH_W) {
                if byte == b'#' {
                    let px = cx + x as u32;
                    let py = cy + y as u32;
                    pixels[(py * ATLAS_W + px) as usize] = 255;
                }
            }
        }
    }
    // The spare cell is solid, for HUD background panels.
    let cx = (SOLID_CELL % COLS) * CELL_W;
    let cy = (SOLID_CELL / COLS) * CELL_H;
    for y in cy..cy + CELL_H {
        for x in cx..cx + CELL_W {
            pixels[(y * ATLAS_W + x) as usize] = 255;
        }
    }
    pixels
}

